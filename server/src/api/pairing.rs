    #[tokio::test]
    async fn pairing_relay_drives_real_core_protocol_end_to_end() {
        use persona_core::sync::pairing::{PairingGuest, PairingHost, PairingMessage};

        let (router, _state) = setup(Some("unused-token")).await;

        // The host creates the session
        let (mut host, invite) = PairingHost::new_invite().unwrap();
        let group_key: [u8; 32] = rand::random();
        let session_id = create_session_for(&router, &invite.salt).await;

        // The guest fetches the salt, starts pairing, and submits the client_public
        let req = HttpRequest::builder()
            .method("GET")
            .uri(format!("/api/v1/pairing/sessions/{session_id}"))
            .body(String::new())
            .unwrap();
        let response = router.clone().oneshot(req).await.unwrap();
        let bytes = axum::body::to_bytes(response.into_body(), usize::MAX)
            .await
            .unwrap()
            .to_vec();
        let info: serde_json::Value = serde_json::from_slice(&bytes).unwrap();
        let salt: Vec<u8> = B64.decode(info["salt"].as_str().unwrap()).unwrap();
        let (mut guest, guest_msg) = PairingGuest::start_message(&invite.code, &salt).unwrap();
        assert_eq!(
            post_message_for(
                &router,
                &session_id,
                "to-host",
                &serde_json::to_vec(&guest_msg).unwrap()
            )
            .await,
            StatusCode::ACCEPTED
        );

        // The host takes the client_public -> ServerOffer -> the fingerprint is now displayable
        let (_, got) = take_for(&router, &session_id, "to-host").await;
        let msg: PairingMessage = serde_json::from_slice(&got[0]).unwrap();
        let reply = host.handle_message(msg, &group_key).unwrap().unwrap();
        assert!(host.fingerprint().is_some());

        assert_eq!(
            post_message_for(
                &router,
                &session_id,
                "to-guest",
                &serde_json::to_vec(&reply).unwrap()
            )
            .await,
            StatusCode::ACCEPTED
        );

        // The guest takes the ServerOffer -> ClientProof -> its fingerprint matches the host's
        let (_, got) = take_for(&router, &session_id, "to-guest").await;
        let msg: PairingMessage = serde_json::from_slice(&got[0]).unwrap();
        let reply = guest.handle_message(msg).unwrap().unwrap();
        assert_eq!(guest.fingerprint(), host.fingerprint());

        assert_eq!(
            post_message_for(
                &router,
                &session_id,
                "to-host",
                &serde_json::to_vec(&reply).unwrap()
            )
            .await,
            StatusCode::ACCEPTED
        );

        // The host takes the ClientProof -> Handoff
        let (_, got) = take_for(&router, &session_id, "to-host").await;
        let msg: PairingMessage = serde_json::from_slice(&got[0]).unwrap();
        let reply = host.handle_message(msg, &group_key).unwrap().unwrap();
        assert_eq!(
            post_message_for(
                &router,
                &session_id,
                "to-guest",
                &serde_json::to_vec(&reply).unwrap()
            )
            .await,
            StatusCode::ACCEPTED
        );

        // The guest takes the Handoff -> pairing complete, group keys match (the relay stays zero-knowledge throughout)
        let (_, got) = take_for(&router, &session_id, "to-guest").await;
        let msg: PairingMessage = serde_json::from_slice(&got[0]).unwrap();
        assert!(guest.handle_message(msg).unwrap().is_none());
        assert_eq!(guest.group_key(), Some(&group_key));

        // Cleanup: after either end DELETEs, the session is no longer accessible
        let req = HttpRequest::builder()
            .method("DELETE")
            .uri(format!("/api/v1/pairing/sessions/{session_id}"))
            .body(String::new())
            .unwrap();
        assert_eq!(
            router.oneshot(req).await.unwrap().status(),
            StatusCode::NO_CONTENT
        );
    }

    #[tokio::test]
    async fn pairing_relay_delete_then_404() {
        let (router, _state) = setup(Some("unused-token")).await;
        let session_id = create_session_for(&router, &[3u8; 16]).await;

        let req = HttpRequest::builder()
            .method("DELETE")
            .uri(format!("/api/v1/pairing/sessions/{session_id}"))
            .body(String::new())
            .unwrap();
        assert_eq!(
            router.clone().oneshot(req).await.unwrap().status(),
            StatusCode::NO_CONTENT
        );
        // After deletion it can no longer be fetched (404), and repeating DELETE is idempotent
        let req = HttpRequest::builder()
            .method("GET")
            .uri(format!("/api/v1/pairing/sessions/{session_id}"))
            .body(String::new())
            .unwrap();
        assert_eq!(
            router.clone().oneshot(req).await.unwrap().status(),
            StatusCode::NOT_FOUND
        );
        let req = HttpRequest::builder()
            .method("DELETE")
            .uri(format!("/api/v1/pairing/sessions/{session_id}"))
            .body(String::new())
            .unwrap();
        assert_eq!(
            router.oneshot(req).await.unwrap().status(),
            StatusCode::NO_CONTENT
        );
    }
