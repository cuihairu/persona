//! Dynamic-passcode pairing relay for sync groups (S1, `docs/sync-group-mode.md`).
//!
//! An account-less mailbox: the session_id is itself the capability token; this layer does
//! not interpret the payload (the client's
//! [`persona_core::sync::pairing::PairingMessage`] JSON bytes) and only sees SRP public
//! messages and AEAD ciphertext envelopes (zero knowledge). TTL, per-direction queue
//! limits and payload limits are enforced here — the online brute-force surface is kept
//! down by "short-lived code + queue limit + single-use session" together. No Bearer on the
//! routes: the pairing peers have no shared credentials to begin with (that is the point of
//! zero accounts), and man-in-the-middle attacks are stopped by the core layer's short
//! fingerprint comparison plus mutual M1/M2 proof.
//!
//! Routes (`/api/v1/pairing/*`):
//! - `POST /sessions`                        create a session (host, carrying the KDF salt)
//! - `GET /sessions/{id}`                    metadata (salt + both directions' queue lengths)
//! - `DELETE /sessions/{id}`                 cleanup after either end completes/abandons
//! - `POST|GET /sessions/{id}/messages/to-host`  guest->host mailbox (GET consumes)
//! - `POST|GET /sessions/{id}/messages/to-guest` host->guest mailbox (GET consumes)
//!
//! GET consumes (fetch and delete): message delivery semantics are exactly "each message is
//! read at most once by the other side"; pulling an empty array means no new messages, so
//! both ends simply poll.

